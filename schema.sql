-- =================================
-- USERS
-- =================================

CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT PRIMARY KEY,
    username TEXT,
    first_name TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);


-- =================================
-- GIVEAWAYS
-- =================================

CREATE TABLE IF NOT EXISTS giveaways (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    creator_id BIGINT NOT NULL
        REFERENCES users(user_id),

    winner_count INTEGER NOT NULL
        CHECK (winner_count > 0),

    prizes JSONB NOT NULL,

    min_users INTEGER NOT NULL
        CHECK (min_users > 0),

    max_users INTEGER NOT NULL
        CHECK (max_users >= min_users),

    duration INTEGER NOT NULL
        CHECK (duration > 0),

    mode TEXT NOT NULL
        CHECK (mode IN ('random', 'referral')),

    target_channel TEXT NOT NULL,

    post_text TEXT NOT NULL,

    status TEXT NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'ended', 'cancelled')),

    ends_at TIMESTAMPTZ NOT NULL,

    created_at TIMESTAMPTZ DEFAULT NOW()
);


-- =================================
-- REQUIRED CHANNELS
-- =================================

CREATE TABLE IF NOT EXISTS required_channels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    giveaway_id BIGINT NOT NULL
        REFERENCES giveaways(id) ON DELETE CASCADE,

    chat_id TEXT NOT NULL,

    title TEXT NOT NULL,

    invite_link TEXT NOT NULL,

    UNIQUE (giveaway_id, chat_id)
);


-- =================================
-- PARTICIPANTS
-- =================================

CREATE TABLE IF NOT EXISTS participants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    giveaway_id BIGINT NOT NULL
        REFERENCES giveaways(id) ON DELETE CASCADE,

    user_id BIGINT NOT NULL
        REFERENCES users(user_id),

    active BOOLEAN NOT NULL DEFAULT TRUE,

    referral_count INTEGER NOT NULL DEFAULT 0
        CHECK (referral_count >= 0),

    referred_by BIGINT
        REFERENCES users(user_id),

    created_at TIMESTAMPTZ DEFAULT NOW(),

    UNIQUE (giveaway_id, user_id),

    CHECK (referred_by IS NULL OR referred_by <> user_id)
);


-- =================================
-- REFERRALS
-- =================================

CREATE TABLE IF NOT EXISTS referrals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    giveaway_id BIGINT NOT NULL
        REFERENCES giveaways(id) ON DELETE CASCADE,

    referrer_id BIGINT NOT NULL
        REFERENCES users(user_id),

    referred_user_id BIGINT NOT NULL
        REFERENCES users(user_id),

    created_at TIMESTAMPTZ DEFAULT NOW(),

    UNIQUE (giveaway_id, referred_user_id),

    CHECK (referrer_id <> referred_user_id)
);


-- =================================
-- WINNERS
-- =================================

CREATE TABLE IF NOT EXISTS winners (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    giveaway_id BIGINT NOT NULL
        REFERENCES giveaways(id) ON DELETE CASCADE,

    user_id BIGINT NOT NULL
        REFERENCES users(user_id),

    position INTEGER NOT NULL
        CHECK (position > 0),

    prize TEXT NOT NULL,

    created_at TIMESTAMPTZ DEFAULT NOW(),

    UNIQUE (giveaway_id, position),

    UNIQUE (giveaway_id, user_id)
);


-- =================================
-- INDEXES
-- =================================

CREATE INDEX IF NOT EXISTS idx_giveaways_status
ON giveaways(status);

CREATE INDEX IF NOT EXISTS idx_giveaways_creator
ON giveaways(creator_id);

CREATE INDEX IF NOT EXISTS idx_participants_giveaway
ON participants(giveaway_id);

CREATE INDEX IF NOT EXISTS idx_referrals_referrer
ON referrals(giveaway_id, referrer_id);

CREATE INDEX IF NOT EXISTS idx_giveaways_ends_at
ON giveaways(ends_at);
